"""Build ``tasks.jsonl`` and ``run.yaml`` from ``scenarios.py`` and the source files.

    python3 build.py           # rewrite the generated files
    python3 build.py --check   # exit 1 when they are out of date

The run spec has to carry the service, agent and checker as inline text, so
this keeps them as ordinary Python files you can edit, lint and test.
"""

from __future__ import annotations

import json
import pathlib
import sys

from scenarios import ASSERTIONS, SCENARIOS

HERE = pathlib.Path(__file__).parent
PROVENANCE = "synthetic; written for this repository; Apache-2.0"


def tasks() -> str:
    rows = []
    for s in SCENARIOS:
        rows.append(
            {
                "id": s["id"],
                "input": s["instruction"],
                "metadata": {
                    "category": s["category"],
                    "provenance": PROVENANCE,
                    # Hidden from the agent: only the checker is given the expectation.
                    "environment": {
                        "checker": {
                            "command": [
                                "python3",
                                "check.py",
                                "--expect",
                                json.dumps(s["expect"], sort_keys=True),
                            ]
                        }
                    },
                },
            }
        )
    return "".join(json.dumps(r, sort_keys=True) + "\n" for r in rows)


def block(name: str, indent: int) -> str:
    """``name`` as a YAML block scalar: the key at ``indent``, its text two further in."""
    pad = " " * (indent + 2)
    text = (HERE / name).read_text().rstrip("\n")
    body = "\n".join(pad + line if line else "" for line in text.split("\n"))
    return f"{' ' * indent}{name}: |\n{body}\n"


def spec() -> str:
    evaluators = "\n".join(
        f"    - {{ref: state-assertion, name: {a}, params: {{assertion: {a}}}}}"
        for a in ASSERTIONS
    )
    gates = "\n".join(f"    - {{metric: {a}, min: 1.0}}" for a in ASSERTIONS)
    return f"""\
# GENERATED by build.py from scenarios.py, shop.py, agent.py and check.py. Edit those.
#
# A support/refund starter suite: {len(SCENARIOS)} synthetic tasks against a small order
# service, graded on the shop's final state. Runs offline with a stand-in agent:
#   evalsi run -f run.yaml             # exit 0: every business rule holds
#   sed 's/agent.py, careful/agent.py, sloppy/' run.yaml > regressed.yaml
#   evalsi run -f regressed.yaml       # exit 3, and the gates name the broken rules
# Replace target.agent with your own agent to evaluate it. See README.md.
apiVersion: evals.si/v1alpha1
kind: EvalRun
metadata: {{name: support-refund}}
spec:
  target:
    agent:
      cli:
        command: [python3, agent.py, careful]
  dataset: {{path: tasks.jsonl}}
  harness: {{}}
  environment:
    files:
{block("shop.py", 6)}{block("agent.py", 6)}    setup:
      - python3 shop.py init
    sandbox: {{min_isolation: namespaced, network: deny}}
    checker:
      # Run in a fresh sandbox that receives only shop.db, so editing shop.py or
      # the checker's interpreter cannot change the grade. Each task adds its
      # own expectation to the command (see tasks.jsonl).
      isolation: clean
      outputs: [shop.db]
      parser: json
      files:
{block("check.py", 8)}      command: [python3, check.py]
  evaluators:
    - ref: task-success
{evaluators}
  trials: 1
  gates:
    - {{metric: task-success, min: 1.0}}
{gates}
"""


def main() -> int:
    generated = {"tasks.jsonl": tasks(), "run.yaml": spec()}
    if "--check" in sys.argv:
        stale = [n for n, text in generated.items() if (HERE / n).read_text() != text]
        for name in stale:
            print(f"{name} is out of date: run python3 build.py", file=sys.stderr)
        return 1 if stale else 0
    for name, text in generated.items():
        (HERE / name).write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
